/* 手写内容：多轮连续决策博弈（Saga）。
 *
 * 注意：本文件不参与 npm run qa:cases，也不会被 scripts/build-case-library.mjs
 * 覆盖。多轮内容之所以不写进 src/data/case-library.ts，是因为那是生成物，
 * 每次跑生成脚本都会整份重写。两条链路只通过 FormalCase.id（caseId）缝合。
 *
 * 内容口径：教材能查到的，标 kind: "textbook" 并给印刷页码；凡是依据教材机理
 * 往下推、但教材没有明确记载的工程后果，一律标 kind: "inference"，UI 上必须
 * 显示为「工程推演」，不能冒充史实。
 */

/** 内容出处 */
export type Provenance =
  | { kind: "textbook"; ref: string }
  | { kind: "inference"; basis: string };

/** 选错之后的工程后果，渲染成后果卡片 */
export type EngineeringConsequence = {
  /** 一句话结论，卡片标题 */
  head: string;
  /** 多久会暴露问题 */
  timeline: string;
  /** 现场症状：工程师在终端和图表上真能看到的东西 */
  symptoms: string[];
  /** 技术根因，必须落到教材某一节 */
  rootCause: string;
  /** 代价：多花了什么，又换来什么新的坑 */
  cost: string;
  /** 可同时包含教材依据与推演说明 */
  provenance: Provenance[];
};

/** 悬停 3 秒后由浩晔老师抛出的点拨，只给方向，不泄露正确项 */
export type AiHint = {
  /** 基础提示：一句反问 + 一条页码线索 */
  text: string;
  /** 同一轮错满 2 次后的加码提示；缺省时回退到 text */
  strongText?: string;
  /** 引导用户去翻的花书印刷页码 */
  page?: number;
};

type OptionBase = {
  /** "A" / "B" / "C"，与旧 ScenarioOption.key 对齐 */
  key: string;
  text: string;
  aiHint: AiHint;
};

/** 可辨识联合：正确项不可能带后果卡，错误项不可能带答对反馈 */
export type DecisionOption = OptionBase &
  (
    | { correct: true; feedback: string }
    | { correct: false; consequence: EngineeringConsequence }
  );

/** 一轮决策 */
export type DecisionRound = {
  /** 1-based，UI 显示「第 N 轮 / 共 M 轮」 */
  index: number;
  /** 阶段名，渲染在时间轴上 */
  stage: string;
  /** 情境：承接上一轮的结果，让用户感到局面是自己造成的 */
  brief: string;
  /** 本轮要回答的问题 */
  ask: string;
  options: DecisionOption[];
};

/** 一个案例的完整博弈 */
export type CaseSaga = {
  /** 对应 FormalCase.id，如 "c02" */
  caseId: string;
  code: string;
  /** 开场白，显示在首轮上方 */
  opening: string;
  rounds: DecisionRound[];
  debrief: {
    summary: string;
    textbookCta: string;
  };
};

